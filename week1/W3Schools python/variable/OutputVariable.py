#the print() function is used to output data
x = "Hello World"
print(x)

#u can output multiple items in the print() function, separated by commas
x = "Python"
y = "is"
z = "awesome"
print(x, y, z)

#u can also use the + operator to output multiple items in the print() function
x = "Python "
y = "is "
z = "awesome"
print(x + y + z)

#for numbers, the + character works as a mathematical operator
x = 5
y = 10
print(x + y)

#The best way to output multiple variables in the print() function is to separate them with commas, which even support different data types:
x = 5
y = "John"
print(x, y)