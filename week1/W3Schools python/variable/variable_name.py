#Rule for Python variable names:
#1. A variable name must start with a letter or the underscore character
#2. A variable name cannot start with a number
#3. A variable name can only contain alphanumeric characters and underscores (A-z, 0-9, and _ )
#4. Variable names are case-sensitive (age, Age and AGE are three different variables)
#5. Variable names cannot be any of the Python keywords.

#Multi Words Variable Names:
#1. Camel Case: Each word, except the first, starts with a capital letter.
myVariableName = "Camel Case"

#2. Pascal Case: Each word starts with a capital letter.
MyVariableName = "Pascal Case"

#3. Snake Case: Each word is separated by an underscore character.
my_variable_name = "Snake Case"